/**
 * Follow-up after funding («متابعة ما بعد الصرف»): Yusr keeps checking, as an independent third party,
 * that the help reached the beneficiary, also after the case closes. Anyone with cases:read sees the
 * board; cases:follow_up logs a call or visit.
 */
import { caseStorySchema, recordFollowupSchema, storyPhotoSchema } from '@yusr/core/schemas';
import { endpoint } from '../endpoint';

const FOLLOWUPS = 'Operations · Follow-up';

export const followupOperations = [
  endpoint({
    id: 'admin.followups.board',
    method: 'GET',
    path: '/admin/followups',
    version: '1',
    access: 'staff',
    tag: FOLLOWUPS,
    summary: 'Funded and closed cases with their latest follow-up, most pressing first',
    permission: 'cases:read',
    returns: 'FollowupCase[]',
    handle: ({ services, ctx }) => services.followups.board(ctx),
  }),
  endpoint({
    id: 'admin.followups.log',
    method: 'GET',
    path: '/admin/cases/:id/followups',
    version: '1',
    access: 'staff',
    tag: FOLLOWUPS,
    summary: 'A funded or closed case’s follow-up log, newest first',
    permission: 'cases:read',
    returns: 'FollowupLog',
    handle: ({ services, ctx, params }) => services.followups.log(params['id']!, ctx),
  }),
  endpoint({
    id: 'admin.followups.record',
    method: 'POST',
    path: '/admin/cases/:id/followups',
    version: '1',
    access: 'staff',
    tag: FOLLOWUPS,
    summary: 'Log a follow-up call or visit (append-only)',
    description: 'Only funded or closed cases. The next check, when given, must be after today (Cairo time).',
    permission: 'cases:follow_up',
    body: recordFollowupSchema,
    status: 201,
    returns: 'FollowupLog',
    handle: ({ services, ctx, params, body }) => services.followups.record(params['id']!, body, ctx),
  }),
  endpoint({
    id: 'admin.stories.photo',
    method: 'PUT',
    path: '/admin/cases/:id/story-photo',
    version: '1',
    access: 'staff',
    tag: FOLLOWUPS,
    summary: 'Add or replace the real photo of a closed case’s «قصص نجاح» story (faces blurred before upload)',
    description: 'JPEG or WebP, up to 450 KB (the hub shrinks pictures before sending). Only closed cases.',
    permission: 'cases:edit',
    body: storyPhotoSchema,
    returns: '{ version: string }',
    handle: ({ services, ctx, params, body }) => services.cases.setStoryPhoto(params['id']!, body, ctx),
  }),
  endpoint({
    id: 'admin.stories.removePhoto',
    method: 'DELETE',
    path: '/admin/cases/:id/story-photo',
    version: '1',
    access: 'staff',
    tag: FOLLOWUPS,
    summary: 'Remove the story photo (the illustrated scene shows again)',
    permission: 'cases:edit',
    returns: '{ removed: true }',
    handle: ({ services, ctx, params }) => services.cases.removeStoryPhoto(params['id']!, ctx),
  }),
  endpoint({
    id: 'admin.stories.list',
    method: 'GET',
    path: '/admin/stories',
    version: '1',
    access: 'staff',
    tag: FOLLOWUPS,
    summary: 'Closed cases as «قصص نجاح» stories, published or not, with their own text',
    permission: 'cases:read',
    returns: 'AdminStory[]',
    handle: ({ services, ctx }) => services.cases.adminStories(ctx),
  }),
  endpoint({
    id: 'admin.stories.save',
    method: 'PUT',
    path: '/admin/stories/:id',
    version: '1',
    access: 'staff',
    tag: FOLLOWUPS,
    summary: 'Set the title, story and outcome a closed case tells in «قصص نجاح», and whether it shows',
    description: 'Arabic is required; an empty English text shows the Arabic. Only closed cases.',
    permission: 'cases:edit',
    body: caseStorySchema,
    returns: '{ saved: true }',
    handle: ({ services, ctx, params, body }) => services.cases.saveStory(params['id']!, body, ctx),
  }),
];
