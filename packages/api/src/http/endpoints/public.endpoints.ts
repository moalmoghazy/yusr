/** Donor-facing API: the catalog, giving (guest checkout included), receipts and case submission. */
import { caseFiltersSchema, createDonationSchema, liveQuerySchema, presignUploadSchema, quoteDonationSchema, submitCaseSchema } from '@yusr/core/schemas';
import { endpoint, header } from '../endpoint';

export const publicEndpoints = [
  endpoint({
    id: 'stats.get',
    method: 'GET',
    path: '/stats',
    version: '1',
    access: 'public',
    tag: 'Catalog',
    summary: 'Headline numbers for the landing page',
    returns: 'PlatformStats',
    cache: { seconds: 60 },
    handle: ({ services }) => services.admin.publicStats(),
  }),

  endpoint({
    id: 'cases.list',
    method: 'GET',
    path: '/cases',
    version: '1',
    access: 'public',
    tag: 'Catalog',
    summary: 'Browse published cases',
    description: 'Filter by category, governorate, completion range, urgency and zakat eligibility. Cursor-paginated.',
    query: caseFiltersSchema,
    returns: 'Page<CaseSummary>',
    cache: { seconds: 15 },
    handle: ({ services, query }) => services.cases.list(query),
  }),

  endpoint({
    id: 'cases.get',
    method: 'GET',
    path: '/cases/:slug',
    version: '1',
    access: 'public',
    tag: 'Catalog',
    summary: 'A case page: story, verified documents (redacted), disbursement plan and recent donations',
    returns: 'CaseDetail',
    cache: { seconds: 15 },
    handle: ({ services, params }) => services.cases.detail(params['slug']!),
  }),

  endpoint({
    id: 'donations.live',
    method: 'GET',
    path: '/donations/live',
    version: '1',
    access: 'public',
    tag: 'Donations',
    summary: 'The latest donations for the live ticker (anonymous donors stay anonymous)',
    query: liveQuerySchema,
    returns: 'LiveDonation[]',
    cache: { seconds: 5 },
    handle: ({ services, query }) => services.donations.live(query.limit),
  }),

  endpoint({
    id: 'donations.quote',
    method: 'POST',
    path: '/donations/quote',
    version: '1',
    access: 'public',
    tag: 'Donations',
    summary: 'Price a donation: provider, fee, amount charged and what reaches the case',
    body: quoteDonationSchema,
    returns: 'DonationBreakdown',
    rateLimit: { name: 'donations:quote', limit: 120, windowSeconds: 60, by: 'ip' },
    handle: ({ services, body }) => services.donations.quoteForCase(body.caseId, body),
  }),

  endpoint({
    id: 'donations.create',
    method: 'POST',
    path: '/donations',
    version: '1',
    access: 'public',
    tag: 'Donations',
    summary: 'Start a donation (guest checkout allowed) and get the next checkout step',
    description:
      'Idempotent: repeating a request with the same Idempotency-Key and body returns the same donation and checkout step; ' +
      'the same key with a different body is refused. The receipt token in the response lets a guest open the receipt.',
    body: createDonationSchema,
    status: 201,
    headers: [{ name: 'Idempotency-Key', required: true, description: '16–128 URL-safe characters, one per donation attempt (a UUID works).' }],
    returns: 'CreateDonationResponse',
    rateLimit: { name: 'donations:create', limit: 30, windowSeconds: 600, by: 'ip' },
    handle: ({ services, ctx, body, request }) => services.donations.create(body, { ...ctx, idempotencyKey: header(request, 'idempotency-key') ?? '' }),
  }),

  endpoint({
    id: 'donations.get',
    method: 'GET',
    path: '/donations/:id',
    version: '1',
    access: 'public',
    tag: 'Donations',
    summary: 'A receipt, for its donor, finance staff, or anyone holding its receipt token',
    headers: [{ name: 'X-Receipt-Token', required: false, description: 'From the create response or the receipt email; lets a guest open the receipt.' }],
    returns: 'DonationReceipt',
    handle: ({ services, ctx, params, request }) => services.donations.receipt(params['id']!, { actor: ctx.actor, token: header(request, 'x-receipt-token') }),
  }),

  endpoint({
    id: 'uploads.create',
    method: 'POST',
    path: '/uploads',
    version: '1',
    access: 'user',
    tag: 'Submissions',
    summary: 'A 10-minute upload link into private storage (step 1 of submitting a document)',
    description: 'PUT the file to the returned URL with the returned headers, then reference its key when submitting the case.',
    body: presignUploadSchema,
    returns: 'UploadTicket',
    handle: ({ services, ctx, body }) => services.documents.presignUpload(body, ctx),
  }),

  endpoint({
    id: 'cases.submit',
    method: 'POST',
    path: '/cases',
    version: '1',
    access: 'user',
    tag: 'Submissions',
    summary: 'Submit a case for review',
    description: 'Starts the pipeline under_review → field_verified → published. A repeat national ID is flagged for reviewers, never rejected.',
    body: submitCaseSchema,
    status: 201,
    returns: 'SubmitCaseResult',
    rateLimit: { name: 'cases:submit', limit: 10, windowSeconds: 86_400, by: 'actor' },
    handle: ({ services, ctx, body }) => services.cases.submit(body, ctx),
  }),
];
